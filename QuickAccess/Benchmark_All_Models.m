
function results = Benchmark_All_Models()
%BENCHMARK_ALL_MODELS Run CPU and CUDA MGPCG for every built-in model.
%
% The benchmark:
%   1. Loads every built-in dataset.
%   2. Builds the FEA hierarchy.
%   3. Runs the CUDA MGPCG solver.
%   4. Runs the CPU MGPCG solver.
%   5. Verifies both solutions using the trusted CPU K*U.
%   6. Compares solution accuracy and runtime.
%   7. Continues to the next model if one model fails.
%   8. Writes the final results to CSV and MAT files.
%
% Usage:
%
%   results = Benchmark_All_Models();
%

    clc;

    addpath('../');
    addpath('../src/');
    addpath('../src/MEXfuncs/');

    outPath = '../out/';

    if ~exist(outPath, 'dir')
        mkdir(outPath);
    end

    modelNames = { ...
        'Bone', ...
        'Part', ...
        'Part2', ...
        'Part3', ...
        'Bracket_GE', ...
        'Molar', ...
        'Fertility', ...
        'Hanger', ...
        'TopOptiShape'};

    numModels = numel(modelNames);

    % -------------------------------------------------------------
    % Preallocate result storage.
    % -------------------------------------------------------------
    status = strings(numModels, 1);
    errorMessage = strings(numModels, 1);

    numLevels = nan(numModels, 1);
    finestElements = nan(numModels, 1);
    finestNodes = nan(numModels, 1);
    finestDOFs = nan(numModels, 1);
    coarsestDOFs = nan(numModels, 1);
    coarsestFreeDOFs = nan(numModels, 1);
    coarseMatrixNNZ = nan(numModels, 1);

    voxelLoadTime = nan(numModels, 1);
    feaSetupTime = nan(numModels, 1);
    stencilAssemblyTime = nan(numModels, 1);
    hierarchyBuildTime = nan(numModels, 1);

    gpuTime = nan(numModels, 1);
    cpuTime = nan(numModels, 1);
    speedup = nan(numModels, 1);

    gpuIterations = nan(numModels, 1);
    gpuReportedRelres = nan(numModels, 1);
    gpuVerifiedRelres = nan(numModels, 1);
    cpuVerifiedRelres = nan(numModels, 1);

    absoluteDifference = nan(numModels, 1);
    relativeDifference = nan(numModels, 1);
    maximumDifference = nan(numModels, 1);

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('CPU vs CUDA MGPCG benchmark for all built-in models\n');
    fprintf('============================================================\n');
    fprintf('Number of models: %d\n', numModels);

    overallTimer = tic;

    for modelIndex = 1:numModels

        modelName = modelNames{modelIndex};

        fprintf('\n\n');
        fprintf('############################################################\n');
        fprintf('Model %d of %d: %s\n', ...
            modelIndex, ...
            numModels, ...
            modelName);
        fprintf('############################################################\n');

        modelTimer = tic;

        try
            modelResult = runSingleModel(modelName);

            status(modelIndex) = "Success";
            errorMessage(modelIndex) = "";

            numLevels(modelIndex) = modelResult.numLevels;
            finestElements(modelIndex) = modelResult.finestElements;
            finestNodes(modelIndex) = modelResult.finestNodes;
            finestDOFs(modelIndex) = modelResult.finestDOFs;
            coarsestDOFs(modelIndex) = modelResult.coarsestDOFs;
            coarsestFreeDOFs(modelIndex) = modelResult.coarsestFreeDOFs;
            coarseMatrixNNZ(modelIndex) = modelResult.coarseMatrixNNZ;

            voxelLoadTime(modelIndex) = modelResult.voxelLoadTime;
            feaSetupTime(modelIndex) = modelResult.feaSetupTime;
            stencilAssemblyTime(modelIndex) = ...
                modelResult.stencilAssemblyTime;
            hierarchyBuildTime(modelIndex) = ...
                modelResult.hierarchyBuildTime;

            gpuTime(modelIndex) = modelResult.gpuTime;
            cpuTime(modelIndex) = modelResult.cpuTime;
            speedup(modelIndex) = modelResult.speedup;

            gpuIterations(modelIndex) = modelResult.gpuIterations;
            gpuReportedRelres(modelIndex) = ...
                modelResult.gpuReportedRelres;
            gpuVerifiedRelres(modelIndex) = ...
                modelResult.gpuVerifiedRelres;
            cpuVerifiedRelres(modelIndex) = ...
                modelResult.cpuVerifiedRelres;

            absoluteDifference(modelIndex) = ...
                modelResult.absoluteDifference;
            relativeDifference(modelIndex) = ...
                modelResult.relativeDifference;
            maximumDifference(modelIndex) = ...
                modelResult.maximumDifference;

            fprintf('\n');
            fprintf('------------------------------------------------------------\n');
            fprintf('Completed model: %s\n', modelName);
            fprintf('Total model benchmark time: %.6f s\n', toc(modelTimer));
            fprintf('CPU solve time:             %.6f s\n', ...
                modelResult.cpuTime);
            fprintf('CUDA end-to-end time:       %.6f s\n', ...
                modelResult.gpuTime);
            fprintf('Measured speedup:           %.3fx\n', ...
                modelResult.speedup);
            fprintf('CPU verified relres:        %.6e\n', ...
                modelResult.cpuVerifiedRelres);
            fprintf('CUDA verified relres:       %.6e\n', ...
                modelResult.gpuVerifiedRelres);
            fprintf('Relative solution error:    %.6e\n', ...
                modelResult.relativeDifference);
            fprintf('------------------------------------------------------------\n');

        catch ME
            status(modelIndex) = "Failed";
            errorMessage(modelIndex) = string(ME.message);

            fprintf('\n');
            fprintf('!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n');
            fprintf('MODEL FAILED: %s\n', modelName);
            fprintf('%s\n', getReport(ME, 'extended', 'hyperlinks', 'off'));
            fprintf('!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n');
        end

        % Construct and save an intermediate table after every model.
        % This preserves completed results if a later model crashes MATLAB.
        results = createResultsTable( ...
            modelNames, ...
            status, ...
            errorMessage, ...
            numLevels, ...
            finestElements, ...
            finestNodes, ...
            finestDOFs, ...
            coarsestDOFs, ...
            coarsestFreeDOFs, ...
            coarseMatrixNNZ, ...
            voxelLoadTime, ...
            feaSetupTime, ...
            stencilAssemblyTime, ...
            hierarchyBuildTime, ...
            gpuTime, ...
            cpuTime, ...
            speedup, ...
            gpuIterations, ...
            gpuReportedRelres, ...
            gpuVerifiedRelres, ...
            cpuVerifiedRelres, ...
            absoluteDifference, ...
            relativeDifference, ...
            maximumDifference);

        save( ...
            fullfile(outPath, 'MGPCG_AllModels_Results.mat'), ...
            'results');

        writetable( ...
            results, ...
            fullfile(outPath, 'MGPCG_AllModels_Results.csv'));
    end

    totalBenchmarkTime = toc(overallTimer);

    fprintf('\n\n');
    fprintf('============================================================\n');
    fprintf('FINAL BENCHMARK RESULTS\n');
    fprintf('============================================================\n');

    summaryColumns = { ...
        'Model', ...
        'Status', ...
        'FinestDOFs', ...
        'GPUIterations', ...
        'CPUTimeSeconds', ...
        'GPUTimeSeconds', ...
        'Speedup', ...
        'CPUVerifiedRelres', ...
        'GPUVerifiedRelres', ...
        'RelativeSolutionDifference'};

    disp(results(:, summaryColumns));

    fprintf('Total benchmark time: %.6f s\n', totalBenchmarkTime);
    fprintf('Successful models:    %d\n', sum(status == "Success"));
    fprintf('Failed models:        %d\n', sum(status == "Failed"));

    successfulSpeedups = speedup(status == "Success");

    if ~isempty(successfulSpeedups)
        fprintf('Mean speedup:          %.3fx\n', ...
            mean(successfulSpeedups, 'omitnan'));
        fprintf('Median speedup:        %.3fx\n', ...
            median(successfulSpeedups, 'omitnan'));
        fprintf('Minimum speedup:       %.3fx\n', ...
            min(successfulSpeedups, [], 'omitnan'));
        fprintf('Maximum speedup:       %.3fx\n', ...
            max(successfulSpeedups, [], 'omitnan'));
    end

    fprintf('\nResults saved to:\n');
    fprintf('%s\n', ...
        fullfile(outPath, 'MGPCG_AllModels_Results.mat'));
    fprintf('%s\n', ...
        fullfile(outPath, 'MGPCG_AllModels_Results.csv'));
end


function result = runSingleModel(modelName)
%RUNSINGLEMODEL Run the complete benchmark for one model.

    global meshHierarchy_;
    global loadingCond_;
    global fixingCond_;
    global F_;
    global U_;
    global tol_;
    global maxIT_;

    % Reset globals so data from the previous model cannot leak into the
    % current model.
    clear global meshHierarchy_;
    clear global loadingCond_;
    clear global fixingCond_;
    clear global F_;
    clear global U_;
    clear global tol_;
    clear global maxIT_;

    global meshHierarchy_;
    global loadingCond_;
    global fixingCond_;
    global F_;
    global U_;
    global tol_;
    global maxIT_;

    Data_GlobalVariables;

    result = struct();

    result.model = modelName;

    % -------------------------------------------------------------
    % 1. Data loading and voxelization
    % -------------------------------------------------------------
    fprintf('\n--- 1. Loading model: %s ---\n', modelName);

    timer = tic;

    IO_LoadBuiltInDatasets(modelName);

    result.voxelLoadTime = toc(timer);

    fprintf('Prepare voxel model time: %.6f s\n', ...
        result.voxelLoadTime);

    % -------------------------------------------------------------
    % 2. FEA setup
    % -------------------------------------------------------------
    fprintf('\n--- 2. Setting up FEA ---\n');

    timer = tic;

    FEA_ApplyBoundaryCondition();
    FEA_SetupVoxelBased();

    densityField = ...
        ones(meshHierarchy_(1).numElements, 1, 'double');

    meshHierarchy_(1).eleModulus = ...
        TopOpti_MaterialInterpolationSIMP(densityField);

    clear densityField;

    result.feaSetupTime = toc(timer);

    fprintf('FEA setup time: %.6f s\n', ...
        result.feaSetupTime);

    % -------------------------------------------------------------
    % 3. Assemble matrix-free stencil
    % -------------------------------------------------------------
    fprintf('\n--- 3. Assembling computing stencil ---\n');

    timer = tic;

    Solving_AssembleFEAstencil();

    result.stencilAssemblyTime = toc(timer);

    fprintf('Stencil assembly time: %.6f s\n', ...
        result.stencilAssemblyTime);

    % -------------------------------------------------------------
    % 4. Build CUDA hierarchy input
    % -------------------------------------------------------------
    fprintf('\n--- 4. Building GPU hierarchy ---\n');

    timer = tic;

    H_ = Build_GPU_Hierarchy(meshHierarchy_);

    result.hierarchyBuildTime = toc(timer);

    fprintf('Hierarchy build time: %.6f s\n', ...
        result.hierarchyBuildTime);

    result.numLevels = double(H_.numLevels);
    result.finestElements = double(H_.numElements(1));
    result.finestNodes = double(H_.numNodes(1));
    result.finestDOFs = double(H_.numDOFs(1));
    result.coarsestDOFs = double(H_.numDOFs(end));
    result.coarsestFreeDOFs = ...
        double(numel(H_.coarseFreeDOFIds));
    result.coarseMatrixNNZ = double(nnz(H_.coarseKFree));

    fprintf('\n--- GPU hierarchy information ---\n');
    fprintf('Number of levels:       %d\n', H_.numLevels);
    fprintf('Finest-level elements:  %d\n', H_.numElements(1));
    fprintf('Finest-level nodes:     %d\n', H_.numNodes(1));
    fprintf('Finest-level DOFs:      %d\n', H_.numDOFs(1));
    fprintf('Coarsest-level DOFs:    %d\n', H_.numDOFs(end));
    fprintf('Coarsest free DOFs:     %d\n', ...
        numel(H_.coarseFreeDOFIds));
    fprintf('Coarse matrix size:     %d x %d\n', ...
        size(H_.coarseKFree, 1), ...
        size(H_.coarseKFree, 2));
    fprintf('Coarse matrix nnz:      %d\n', ...
        nnz(H_.coarseKFree));
    fprintf('Jacobi omega:           %.6f\n', ...
        H_.jacobiOmega);

    validateHierarchy(H_);

    % -------------------------------------------------------------
    % 5. Prepare common solver input
    % -------------------------------------------------------------
    F_ = full(double(F_(:)));

    U0 = zeros(size(F_), 'double');

    for level = 1:H_.numLevels - 1
        H_.diagK{level} = ...
            full(double(H_.diagK{level}(:)));
    end

    H_.eleModulus{1} = ...
        full(double(H_.eleModulus{1}(:)));

    H_.Ke = full(double(H_.Ke));

    mexPath = which('Solving_MGPCG_GPU_fixed');

    if isempty(mexPath)
        error( ...
            'Benchmark:MissingCUDAFunction', ...
            ['Solving_MGPCG_GPU_fixed was not found. ', ...
             'Compile the CUDA MEX and add its directory ', ...
             'to the MATLAB path.']);
    end

    fprintf('\nUsing CUDA MEX:\n%s\n', mexPath);

    % -------------------------------------------------------------
    % 6. CUDA solve
    % -------------------------------------------------------------
    fprintf('\n--- 5. Running CUDA MGPCG ---\n');

    gpuTimer = tic;

    [U_gpu, gpuIterations, gpuReportedRelres] = ...
        Solving_MGPCG_GPU_fixed( ...
            F_, ...
            tol_, ...
            maxIT_, ...
            U0, ...
            H_);

    result.gpuTime = toc(gpuTimer);
    result.gpuIterations = double(gpuIterations);
    result.gpuReportedRelres = double(gpuReportedRelres);

    fprintf('CUDA end-to-end time: %.6f s\n', ...
        result.gpuTime);
    fprintf('CUDA iterations:      %d\n', ...
        result.gpuIterations);
    fprintf('CUDA reported relres: %.6e\n', ...
        result.gpuReportedRelres);

    if any(~isfinite(U_gpu))
        error( ...
            'Benchmark:InvalidGPUSolution', ...
            'CUDA solution for model %s contains NaN or Inf.', ...
            modelName);
    end

    % -------------------------------------------------------------
    % 7. CPU solve
    % -------------------------------------------------------------
    fprintf('\n--- 6. Running CPU MGPCG ---\n');

    cpuTimer = tic;

    U_cpu = Solving_PreconditionedConjugateGradientSolver( ...
        @Solving_KbyU_MatrixFree, ...
        @Solving_Vcycle, ...
        F_, ...
        tol_, ...
        maxIT_, ...
        'printP_ON', ...
        U0);

    result.cpuTime = toc(cpuTimer);

    fprintf('CPU solve time: %.6f s\n', result.cpuTime);

    if any(~isfinite(U_cpu))
        error( ...
            'Benchmark:InvalidCPUSolution', ...
            'CPU solution for model %s contains NaN or Inf.', ...
            modelName);
    end

    % -------------------------------------------------------------
    % 8. Verify both solutions using trusted CPU K*U
    % -------------------------------------------------------------
    fprintf('\n--- 7. Verifying solutions with CPU K*U ---\n');

    KU_cpu = Solving_KbyU_MatrixFree(U_cpu);
    KU_gpu = Solving_KbyU_MatrixFree(U_gpu);

    r_cpu = F_ - KU_cpu;
    r_gpu = F_ - KU_gpu;

    fixedDOFs = meshHierarchy_(1).fixedDOFs(:);

    r_cpu(fixedDOFs) = 0;
    r_gpu(fixedDOFs) = 0;

    normF = norm(F_);

    if normF == 0
        normF = 1;
    end

    result.cpuVerifiedRelres = norm(r_cpu) / normF;
    result.gpuVerifiedRelres = norm(r_gpu) / normF;

    % -------------------------------------------------------------
    % 9. Compare displacement vectors
    % -------------------------------------------------------------
    result.absoluteDifference = norm(U_gpu - U_cpu);

    result.relativeDifference = ...
        result.absoluteDifference / max(norm(U_cpu), eps);

    result.maximumDifference = ...
        max(abs(U_gpu - U_cpu));

    result.speedup = result.cpuTime / result.gpuTime;

    fprintf('\n--- Accuracy results ---\n');
    fprintf('CPU verified relres:          %.6e\n', ...
        result.cpuVerifiedRelres);
    fprintf('CUDA verified relres:         %.6e\n', ...
        result.gpuVerifiedRelres);
    fprintf('CUDA internally reported:     %.6e\n', ...
        result.gpuReportedRelres);
    fprintf('||U_gpu - U_cpu||:            %.6e\n', ...
        result.absoluteDifference);
    fprintf('Relative solution difference: %.6e\n', ...
        result.relativeDifference);
    fprintf('Maximum entry difference:     %.6e\n', ...
        result.maximumDifference);

    fprintf('\n--- Runtime results ---\n');
    fprintf('CPU solve time:       %.6f s\n', ...
        result.cpuTime);
    fprintf('CUDA end-to-end time: %.6f s\n', ...
        result.gpuTime);
    fprintf('Measured speedup:     %.3fx\n', ...
        result.speedup);

    % -------------------------------------------------------------
    % 10. Validation warnings
    % -------------------------------------------------------------
    if result.gpuVerifiedRelres > max(10 * tol_, 1e-8)
        warning( ...
            'Benchmark:LargeGPUResidual', ...
            ['Model %s: CUDA verified residual %.6e is larger ', ...
             'than the requested tolerance %.6e.'], ...
            modelName, ...
            result.gpuVerifiedRelres, ...
            tol_);
    end

    if result.relativeDifference > 1e-5
        warning( ...
            'Benchmark:SolutionDifference', ...
            ['Model %s: CPU and CUDA solutions differ ', ...
             'significantly. Relative difference: %.6e.'], ...
            modelName, ...
            result.relativeDifference);
    end

    residualDifference = abs( ...
        result.gpuReportedRelres - ...
        result.gpuVerifiedRelres);

    residualThreshold = max( ...
        1e-8, ...
        1e-3 * result.gpuVerifiedRelres);

    if residualDifference > residualThreshold
        warning( ...
            'Benchmark:ResidualMismatch', ...
            ['Model %s: CUDA reported residual and externally ', ...
             'verified residual differ significantly. ', ...
             'Reported: %.6e, verified: %.6e.'], ...
            modelName, ...
            result.gpuReportedRelres, ...
            result.gpuVerifiedRelres);
    end

    % Keep the GPU result as the active solution for any calculations
    % performed before this local function exits.
    U_ = U_gpu;
end


function validateHierarchy(H_)
%VALIDATEHIERARCHY Validate fields required by the CUDA solver.

    assert( ...
        issparse(H_.coarseKFree), ...
        'H_.coarseKFree must remain sparse.');

    assert( ...
        size(H_.coarseKFree, 1) == ...
        numel(H_.coarseFreeDOFIds), ...
        'coarseKFree size does not match coarseFreeDOFIds.');

    assert( ...
        size(H_.coarseKFree, 2) == ...
        numel(H_.coarseFreeDOFIds), ...
        'coarseKFree must be square.');

    assert( ...
        all(isfinite(nonzeros(H_.coarseKFree))), ...
        'coarseKFree contains NaN or Inf.');

    assert( ...
        all(isfinite(H_.Ke(:))), ...
        'H_.Ke contains NaN or Inf.');

    assert( ...
        all(isfinite(H_.eleModulus{1}(:))), ...
        'H_.eleModulus{1} contains NaN or Inf.');

    for level = 1:H_.numLevels - 1
        assert( ...
            all(isfinite(H_.diagK{level}(:))), ...
            'H_.diagK{%d} contains NaN or Inf.', ...
            level);

        assert( ...
            all(H_.diagK{level}(:) ~= 0), ...
            'H_.diagK{%d} contains zero diagonal entries.', ...
            level);
    end
end


